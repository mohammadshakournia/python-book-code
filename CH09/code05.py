def log_calls(func):
    def wrapper(*args, **kwargs):
        print(f"Calling {func.__name__} with args={args}, kwargs={kwargs}")
        result = func(*args, **kwargs)
        print(f"{func.__name__} returned {result}")
        return result
    return wrapper

@log_calls
def add(a, b):
    return a + b

@log_calls
def join_words(a, b, sep=" "):
    return a + sep + b

print("add result:", add(2, 5))
print("join result:", join_words("Hello", "World", sep="-"))
