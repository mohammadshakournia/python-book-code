from functools import wraps

def log_calls(func):
    @wraps(func)
    def wrapper(*args, **kwargs):
        print(f"Calling {func.__name__}")
        return func(*args, **kwargs)
    return wrapper

@log_calls
def greet(name):
    """Say hello to someone."""
    return f"Hello, {name}!"

print("Function name:", greet.__name__)
print("Docstring:", greet.__doc__)
print(greet("Sara"))
