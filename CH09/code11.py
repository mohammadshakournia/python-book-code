# file: 10_class_decorator.py
from functools import wraps

class CountCalls:
    def __init__(self, func):
        wraps(func)(self)
        self.func = func
        self.count = 0

    def __call__(self, *args, **kwargs):
        self.count += 1
        print(f"{self.func.__name__} call #{self.count}")
        return self.func(*args, **kwargs)

@CountCalls
def hello(name):
    print(f"Hello, {name}!")

hello("Sara")
hello("Reza")
