import matplotlib.pyplot as plt

x = [0, 1, 2, 3, 4, 5]
y1 = [0, 1, 4, 9, 16, 25]
y2 = [0, 1, 2, 3, 4, 5]

plt.plot(x, y1, linestyle="-", marker="o", linewidth=2, label="y=x^2")
plt.plot(x, y2, linestyle="--", marker="s", linewidth=2, label="y=x")

plt.legend()
plt.show()
